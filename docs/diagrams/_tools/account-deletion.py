#!/usr/bin/env python3
"""Generates docs/diagrams/account-deletion.svg."""
import os
from lib import Diagram, C

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'account-deletion.svg')
d = Diagram(2000, 1160, 'Account deletion and data export',
            'Deletion is scheduled 30 days out as a delayed job and can be cancelled until it fires; export is a separate on-demand job.')
LT = '#3B37A8'
W = 260
X = [40, 380, 720, 1060, 1400]

d.label(40, 130, 'SCHEDULE')
d.node(X[0], 160, W, 80, 'User', 'account settings', C['dark'])
d.compute(X[1], 160, W, 80, 'DELETE /api/users/me', 'session + rate limit')
d.compute(X[2], 160, W, 80, 'deleteAccount', 'AccountLifecycleService')
d.node(X[3], 160, W, 80, 'deletionScheduledAt', 'now + 30 days · User row', C['red'])
d.node(X[4], 160, 320, 80, 'account-lifecycle queue', 'delayed delete-account job', C['orange'])
for i in range(3):
    d.path([(X[i] + W, 200), (X[i + 1], 200)], 'purple')
    d.pill(X[i] + W + 40, 180, str(i + 1), 'purple')
d.path([(X[3] + W, 200), (X[4], 200)], 'orange')
d.pill(X[3] + W + 40, 180, '4', 'orange')
d.note(X[2] + W / 2, 262, 'sole OWNER of a shared workspace: 409', col=LT)
d.note(X[3] + W / 2, 262, 'sessions deleted · UserCache invalidated', col=LT)
d.note(X[3] + W / 2, 282, 'confirmation e-mail sent', col=LT)
d.note(X[4] + 130, 262, 'jobId per user', col=LT)
d.note(X[4] + 130, 282, 'enqueue fails: schedule cleared', col=LT)

d.label(380, 338, 'GRACE PERIOD ENDS · WORKER')
d.node(X[0], 360, W, 80, 'Delay elapsed', 'scheduledAt reached', C['orange'])
d.path([(X[4] + 300, 240), (X[4] + 300, 305), (X[0] + W / 2, 305), (X[0] + W / 2, 360)], 'orange')
d.pill(900, 305, '5 after 30 days', 'orange')
d.compute(X[1], 360, W, 80, 'processDeleteAccount', 'reads the user')
d.compute(X[2], 360, W, 80, 'Still scheduled?', 'deletionScheduledAt set')
d.compute(X[3], 360, W, 80, 'deleteHard', 'prisma.user.delete')
d.node(X[4], 360, 320, 80, 'Postgres', 'user row gone · onDelete Cascade', C['red'])
d.path([(X[0] + W, 400), (X[1], 400)], 'purple')
d.path([(X[1] + W, 400), (X[2], 400)], 'purple')
d.path([(X[2] + W, 400), (X[3], 400)], 'purple')
d.pill(X[2] + W + 40, 380, 'yes', 'purple')
d.path([(X[3] + W, 400), (X[4], 400)], 'purple')
d.pill(X[3] + W + 40, 380, '6', 'purple')
d.node(X[2], 490, W, 70, 'Skipped', 'deletion_canceled · user_not_found', C['dark'])
d.path([(X[2] + W / 2, 440), (X[2] + W / 2, 490)], 'gray')
d.pill(X[2] + W / 2, 465, 'no', 'gray')
d.note(X[3] + W / 2, 462, 'UserCache invalidated, then logged', col=LT)

d.group(30, 600, 1940, 220, 'CANCEL PATH · BEFORE THE JOB FIRES')
d.compute(60, 640, 320, 70, 'DELETE /api/users/me/deletion', 'explicit cancel')
d.compute(60, 730, 320, 70, 'Sign in again', 'session.create hook')
d.compute(480, 685, 280, 80, 'cancelDeletion', 'AccountLifecycleService')
d.path([(380, 675), (430, 675), (430, 715), (480, 715)], 'blue')
d.path([(380, 765), (430, 765), (430, 735), (480, 735)], 'blue')
d.pill(430, 695, 'a', 'blue')
d.pill(430, 755, 'b', 'blue')
d.node(860, 685, 290, 80, 'Delayed job removed', 'cancelAccountDeletion', C['orange'])
d.node(1230, 685, 290, 80, 'deletionScheduledAt', 'set back to null', C['red'])
d.compute(1600, 685, 340, 80, 'UserCache.invalidate', 'audit user cancel')
d.path([(760, 725), (860, 725)], 'blue')
d.pill(810, 705, '1', 'blue')
d.path([(1150, 725), (1230, 725)], 'blue')
d.pill(1190, 705, '2', 'blue')
d.path([(1520, 725), (1600, 725)], 'blue')
d.pill(1560, 705, '3', 'blue')
d.note(1000, 790, 'a login during the grace period cancels silently; the processor still re-checks the schedule', col=LT)

d.label(40, 880, 'DATA EXPORT · SEPARATE JOB')
d.node(X[0], 910, W, 80, 'User', 'POST /api/users/me/export', C['dark'])
d.compute(X[1], 910, W, 80, 'requestExport', 'exportLimiter per user')
d.node(X[2], 910, W, 80, 'data-export queue', 'export-user-data', C['orange'])
d.compute(X[3], 910, W, 80, 'processDataExport', 'worker')
d.path([(X[0] + W, 950), (X[1], 950)], 'teal')
d.pill(X[0] + W + 40, 930, '1', 'teal')
d.path([(X[1] + W, 950), (X[2], 950)], 'orange')
d.pill(X[1] + W + 40, 930, '2', 'orange')
d.path([(X[2] + W, 950), (X[3], 950)], 'orange')
d.pill(X[2] + W + 40, 930, '3', 'orange')
d.node(X[4], 900, 300, 60, 'Postgres', 'profile · sessions · accounts · consents', C['red'])
d.node(1760, 900, 200, 60, 'Axiom', 'audit, max 5000', C['dark'])
d.path([(X[3] + W, 940), (X[4], 930)], 'teal')
d.pill(X[3] + W + 40, 910, '4', 'teal')
d.path([(X[3] + 160, 910), (X[3] + 160, 880), (1860, 880), (1860, 900)], 'teal')
d.node(X[3], 1040, W, 80, 'Silo', 'bucket user-exports', C['dark'])
d.path([(X[3] + 130, 990), (X[3] + 130, 1040)], 'teal')
d.pill(X[3] + 130, 1015, '5 put JSON', 'teal')
d.node(X[4], 1040, W, 80, 'E-mail (Resend)', 'presigned link, 7 days', C['dark'])
d.path([(X[3] + W, 1080), (X[4], 1080)], 'teal')
d.pill(X[3] + W + 40, 1060, '6', 'teal')
d.save(OUT)
